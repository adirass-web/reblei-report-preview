/* Run against local files with networking disabled. Playwright is a QA dependency only. */
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const {pathToFileURL} = require('node:url');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const {createHash} = require('node:crypto');
const {fileURLToPath} = require('node:url');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'review');
const url = name => pathToFileURL(path.join(root, name)).href;
const visible = page => page.locator('.record:not([hidden])').count();
(async () => {
  const browser = await chromium.launch({headless:true});
  const context = await browser.newContext({offline:true, viewport:{width:1440,height:1000}});
  const page = await context.newPage();
  const errors = [], network = [], checks = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', msg => {if(msg.type() === 'error') errors.push(msg.text());});
  context.on('request', req => {if(/^https?:/.test(req.url())) network.push(req.url());});
  try {
    await page.goto(url('index.html'));
    assert.equal(await page.locator('h1').count(),1);
    assert.match(await page.locator('h1').innerText(),/Michael Edward Bleich/);
    assert(await page.locator('html').evaluate(el=>el.classList.contains('js-ready')));
    await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(()=>document.activeElement.className),'skip');
    await page.keyboard.press('Enter');
    assert.equal(await page.evaluate(()=>document.activeElement.id),'main');
    checks.push('file protocol, offline local CSS/JS, keyboard skip link');
    await page.evaluate(()=>{document.activeElement.blur();window.scrollTo(0,0)});
    await page.screenshot({path:path.join(output,'report-desktop.png'),fullPage:false});
    await page.evaluate(()=>window.dispatchEvent(new Event('beforeprint')));
    await page.emulateMedia({media:'print'});
    assert.equal(await page.locator('.site-header').isVisible(),false);
    await page.pdf({path:path.join(output,'report-print-sample.pdf'),format:'A4',printBackground:true});
    await page.emulateMedia({media:'screen'});
    await page.evaluate(()=>window.dispatchEvent(new Event('afterprint')));
    checks.push('report print output generated with navigation hidden');
    await page.goto(url('claims.html'));
    assert.equal(await visible(page),247);
    await page.locator('#search').fill('INF3-C005');
    await page.waitForFunction(()=>document.querySelector('#result-count').textContent==='1 of 247 records shown');
    assert.match(await page.locator('.record:not([hidden])').innerText(),/unverified|unresolved|does not/i);
    await page.locator('#reset').click();
    await page.locator('[data-filter="entity-person"]').selectOption({label:'Michael Edward Bleich'});
    const subjectCount=await visible(page);assert(subjectCount>0&&subjectCount<247);
    await page.locator('[data-filter="topic-ui-group"]').selectOption({label:'Identity & employment'});
    assert((await visible(page))>0&&(await visible(page))<=subjectCount);
    await page.locator('#search').fill('NO_SUCH_RECORD_TEST');
    await page.waitForFunction(()=>!document.querySelector('#empty-state').hidden);
    assert.equal(await visible(page),0);
    const hiddenId=await page.locator('[data-record-id="EVT-C001"]').getAttribute('id');
    await page.evaluate(id=>{location.hash=id},hiddenId);
    await page.waitForFunction(()=>!document.querySelector('[data-record-id="EVT-C001"]').hidden);
    assert.equal(await page.locator('#search').inputValue(),'');
    assert(await page.locator('[data-record-id="EVT-C001"] details').getAttribute('open')!==null);
    checks.push('claim search, entity/topic AND filters, empty state, hidden-target fragment reveal');
    await page.locator('#search').fill('EVT-C001');
    await page.waitForFunction(()=>document.querySelector('#result-count').textContent==='1 of 247 records shown');
    await page.screenshot({path:path.join(output,'claim-desktop.png'),fullPage:false});
    await page.evaluate(()=>window.dispatchEvent(new Event('beforeprint')));
    await page.emulateMedia({media:'print'});
    assert.equal(await page.locator('.record:visible').count(),1);
    assert(await page.locator('[data-record-id="EVT-C001"] details').isVisible());
    await page.pdf({path:path.join(output,'claim-print-sample.pdf'),format:'A4',printBackground:true});
    await page.emulateMedia({media:'screen'});
    await page.evaluate(()=>window.dispatchEvent(new Event('afterprint')));
    checks.push('filtered record print preserves exact claim and source details');
    await page.goto(url('documents.html'));
    assert.equal(await visible(page),396);
    await page.locator('#search').fill('id-finra-scout-151990');
    await page.waitForFunction(()=>document.querySelector('#result-count').textContent==='1 of 396 records shown');
    const pdf=page.locator('.record:not([hidden]) a[href$=".pdf"]').first();
    const target=new URL(await pdf.getAttribute('href'),page.url()).href;
    const pdfPage=await context.newPage();
    const downloaded=pdfPage.waitForEvent('download');
    await pdfPage.goto(target).catch(error=>{if(!error.message.includes('Download is starting')) throw error;});
    const download=await downloaded;
    const downloadedPath=await download.path();
    const hash=p=>createHash('sha256').update(fs.readFileSync(p)).digest('hex');
    assert.equal(hash(downloadedPath),hash(fileURLToPath(target)));
    await download.delete();
    await pdfPage.close();
    await page.locator('#reset').click();
    await page.locator('[data-filter="source-class"]').selectOption({label:'official_filing_or_record'});
    assert((await visible(page))>0 && (await visible(page))<396);
    await page.locator('[data-filter="date-basis"]').selectOption({label:'Filing date not established'});
    assert((await visible(page))>0);
    checks.push('document search, source/date facets and local PDF retrieval; headless Chromium downloads PDF and its SHA256 matches original');
    for (const name of ['index.html','claims.html','documents.html','follow-up.html','issues.html','entities.html','events.html','financial.html','about.html']) {
      await page.setViewportSize({width:390,height:844});
      await page.goto(url(name));
      assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),name+' overflows horizontally');
      if(name==='index.html') await page.screenshot({path:path.join(output,'report-mobile.png'),fullPage:false});
    }
    checks.push('all nine pages fit a 390px viewport; wide source tables scroll within their containers');
    const noJS=await browser.newContext({offline:true,javaScriptEnabled:false});
    const plain=await noJS.newPage();
    await plain.goto(url('claims.html'));
    assert.equal(await plain.locator('.record').count(),247);
    assert.equal(await plain.locator('#search').isVisible(),false);
    assert.equal(await plain.locator('noscript').isVisible(),true);
    await plain.goto(url('index.html'));
    assert.match(await plain.locator('main').innerText(),/Inferent remains a conditional affiliation/);
    await noJS.close();
    checks.push('no-JavaScript report and full claim catalogue remain readable');
    assert.deepEqual(network,[],'Unexpected automatic internet request');
    assert.deepEqual(errors,[],'Browser errors');
    const result={checked_at_utc:new Date().toISOString(),browser:await browser.version(),protocol:'file:',network:'disabled',checks,automatic_http_requests:network.length,console_or_page_errors:errors.length,status:'passed'};
    fs.writeFileSync(path.join(output,'browser-validation.json'),JSON.stringify(result,null,2)+'\n');
    console.log(JSON.stringify(result,null,2));
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
